ENTITY_REF_RE = re.compile(r"&([A-Za-z][A-Za-z0-9]*);")

# XML 1.0 predefined entities; valid in any well-formed document without a DTD subset.
XML_PREDEFINED_ENTITIES = frozenset({"amp", "lt", "gt", "quot", "apos"})


def entity_refs_in(text: str) -> set[str]:
    refs = set(ENTITY_REF_RE.findall(text))
    return refs - XML_PREDEFINED_ENTITIES


def internal_subset_declarations(text: str) -> str:
    """Return internal DTD subset lines for every DBLP entity reference in text."""
    refs = entity_refs_in(text)
    if not refs:
        return ""
    lines: list[str] = []
    for name in sorted(refs):
        replacement = DBLP_NAMED_ENTITIES.get(name)
        if replacement is None:
            raise ValueError(f"unsupported DBLP entity reference &{name}; in excerpt")
        lines.append(f'<!ENTITY {name} "{replacement}">')
    return "\n".join(lines)


def dblp_sample_prolog(record_xml: str) -> str:
    subset = internal_subset_declarations(record_xml)
    if subset:
        doctype = f"<!DOCTYPE dblp [\n{subset}\n]>\n"
    else:
        doctype = "<!DOCTYPE dblp []>\n"
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!-- ScholarChain sample regenerated by datasets/scripts/acquire_samples.py -->\n"
        f"{doctype}"
    )
