#!/usr/bin/env python3
"""Local-state binding, materialized-source hashing and receipt checks (stdlib; python3 -I).

The Terraform root uses the LOCAL backend. A plan made from a materialized copy of the source (a `git archive`
in a private run directory) would otherwise see a fresh, empty state. This module generates the backend override
that points the copy at the live state file, records the state identity (lineage, serial, sha256) so apply can
refuse a missing, replaced or changed state, and hashes the materialized source tree.

Only the lineage, the serial and the sha256 of the state file are ever read out of it or printed: no resource
value, output or attribute leaves this module.

  inspect       --state PATH                        print JSON {"present", "lineage", "serial", "sha256"}
                                                    (exit 1: unreadable, not a Terraform state, or a symlink)
  write-binding --root DIR --state ABS              write zz_scholarchain_state_binding.tf into DIR (exclusive
                                                    create); refuse when DIR already declares a backend
  tree-hash     --root DIR                          sha256 over sorted "path sha256 size exec" lines
  check         --state PATH --receipt FILE         the live state must equal the receipt's "state" record
  check-tree    --receipt FILE --tree-sha256 H      the receipt's source_tree_sha256 must equal H
  receipt-field --receipt FILE --key K              print one scalar receipt field (empty when null)
"""
import argparse
import hashlib
import json
import os
import re
import stat
import sys

BINDING_FILE = "zz_scholarchain_state_binding.tf"
SAFE_PATH = re.compile(r"^[A-Za-z0-9_./ @+=,:-]+$")
BACKEND_BLOCK = re.compile(r'^\s*backend\s+"', re.M)
FIELD_KEYS = ("source_tree_sha256", "image_revision", "purpose", "commit", "env", "planned_environment", "planned_project")


def sha256_file(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def inspect_state(path):
    """Return the state identity dict, or raise ValueError with a safe message."""
    try:
        mode = os.lstat(path).st_mode
    except FileNotFoundError:
        return {"present": False}
    if stat.S_ISLNK(mode):
        raise ValueError("the state file path is a symlink")
    if not stat.S_ISREG(mode):
        raise ValueError("the state file path is not a regular file")
    digest = sha256_file(path)
    try:
        with open(path, encoding="utf-8") as handle:
            document = json.load(handle)
    except (OSError, ValueError):
        raise ValueError("the state file is not valid JSON")
    if not isinstance(document, dict) or not isinstance(document.get("lineage"), str) or isinstance(document.get("serial"), bool) or not isinstance(document.get("serial"), int):
        raise ValueError("the file is not a Terraform state (no lineage and serial)")
    return {"present": True, "lineage": document["lineage"], "serial": document["serial"], "sha256": digest}


def cmd_inspect(args):
    try:
        identity = inspect_state(args.state)
    except ValueError as error:
        print("STATE-BINDING-FAILED: %s" % error)
        return 1
    print(json.dumps(identity, sort_keys=True))
    return 0


def cmd_write_binding(args):
    if not os.path.isabs(args.state) or not SAFE_PATH.match(args.state) or ".." in args.state.split(os.sep):
        print("STATE-BINDING-FAILED: the live state path holds characters that cannot be bound safely")
        return 1
    root = args.root
    for name in sorted(os.listdir(root)):
        path = os.path.join(root, name)
        if name == BINDING_FILE:
            print("STATE-BINDING-FAILED: the source already holds %s" % BINDING_FILE)
            return 1
        if name.endswith((".tf", ".tf.json")) and os.path.isfile(path):
            with open(path, encoding="utf-8", errors="replace") as handle:
                if name.endswith(".tf") and BACKEND_BLOCK.search(handle.read()):
                    print("STATE-BINDING-FAILED: %s declares a backend block; the rollback target must use the local backend like the live stack" % name)
                    return 1
            if name.endswith(".tf.json"):
                with open(path, encoding="utf-8", errors="replace") as handle:
                    if '"backend"' in handle.read():
                        print("STATE-BINDING-FAILED: %s declares a backend; refusing" % name)
                        return 1
    body = (
        "# Generated by scripts/lib/state_bind.py. Binds this materialized root to the LIVE local state file so a plan\n"
        "# or apply never starts from a fresh, empty state.\n"
        "terraform {\n"
        '  backend "local" {\n'
        '    path = "%s"\n'
        "  }\n"
        "}\n" % args.state
    )
    descriptor = os.open(os.path.join(root, BINDING_FILE), os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
        handle.write(body)
    print("wrote %s" % BINDING_FILE)
    return 0


def tree_lines(root):
    lines = []
    for base, dirs, files in os.walk(root):
        dirs.sort()
        for name in sorted(files + [d for d in dirs if os.path.islink(os.path.join(base, d))]):
            path = os.path.join(base, name)
            rel = os.path.relpath(path, root).replace(os.sep, "/")
            if os.path.islink(path):
                lines.append("%s link %s" % (rel, os.readlink(path)))
                continue
            info = os.stat(path)
            lines.append("%s %s %d %d" % (rel, sha256_file(path), info.st_size, 1 if info.st_mode & stat.S_IXUSR else 0))
    lines.sort()
    return lines


def cmd_tree_hash(args):
    if not os.path.isdir(args.root):
        print("TREE-HASH-FAILED: not a directory")
        return 1
    print(hashlib.sha256("\n".join(tree_lines(args.root)).encode("utf-8")).hexdigest())
    return 0


def _read_receipt(path):
    try:
        with open(path, encoding="utf-8") as handle:
            document = json.load(handle)
    except (OSError, ValueError):
        return None
    return document if isinstance(document, dict) else None


def cmd_check(args):
    receipt = _read_receipt(args.receipt)
    if receipt is None or not isinstance(receipt.get("state"), dict) or not isinstance(receipt["state"].get("present"), bool):
        print("STATE-BINDING-FAILED: the plan receipt holds no state record (re-run plan.sh)")
        return 1
    expected = receipt["state"]
    try:
        live = inspect_state(args.state)
    except ValueError as error:
        print("STATE-BINDING-FAILED: %s" % error)
        return 1
    problems = []
    if not expected["present"]:
        if live["present"]:
            problems.append("a state file now exists but the plan was made for a first deployment with no state")
    elif not live["present"]:
        problems.append("the live state file is missing (the plan was made against existing state)")
    else:
        if live["lineage"] != expected.get("lineage"):
            problems.append("the live state lineage differs from the plan receipt (a different stack's state)")
        elif live["serial"] != expected.get("serial") or live["sha256"] != expected.get("sha256"):
            problems.append("the live state changed after the plan was made (serial %s, receipt serial %s); plan again" % (live["serial"], expected.get("serial")))
    for problem in problems:
        print("STATE-BINDING-FAILED: %s" % problem)
    if not problems:
        if live["present"]:
            print("state binding ok: lineage %s serial %s sha256 %s" % (live["lineage"], live["serial"], live["sha256"]))
        else:
            print("state binding ok: no state file, as recorded for a first deployment")
    return 1 if problems else 0


def cmd_check_tree(args):
    receipt = _read_receipt(args.receipt)
    if receipt is None or not re.fullmatch(r"[0-9a-f]{64}", str(receipt.get("source_tree_sha256", ""))):
        print("SOURCE-TREE-FAILED: the plan receipt holds no source_tree_sha256 (re-run plan.sh)")
        return 1
    if receipt["source_tree_sha256"] != args.tree_sha256:
        print("SOURCE-TREE-FAILED: the materialized source differs from the source the plan was made from")
        return 1
    print("source tree ok: sha256 %s" % args.tree_sha256)
    return 0


def cmd_receipt_field(args):
    if args.key not in FIELD_KEYS:
        print("not a readable field", file=sys.stderr)
        return 2
    receipt = _read_receipt(args.receipt)
    if receipt is None:
        return 1
    value = receipt.get(args.key)
    print("" if value is None else str(value))
    return 0


def build_parser():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("inspect")
    p.add_argument("--state", required=True)
    p.set_defaults(fn=cmd_inspect)
    p = sub.add_parser("write-binding")
    p.add_argument("--root", required=True)
    p.add_argument("--state", required=True)
    p.set_defaults(fn=cmd_write_binding)
    p = sub.add_parser("tree-hash")
    p.add_argument("--root", required=True)
    p.set_defaults(fn=cmd_tree_hash)
    p = sub.add_parser("check")
    p.add_argument("--state", required=True)
    p.add_argument("--receipt", required=True)
    p.set_defaults(fn=cmd_check)
    p = sub.add_parser("check-tree")
    p.add_argument("--receipt", required=True)
    p.add_argument("--tree-sha256", required=True)
    p.set_defaults(fn=cmd_check_tree)
    p = sub.add_parser("receipt-field")
    p.add_argument("--receipt", required=True)
    p.add_argument("--key", required=True)
    p.set_defaults(fn=cmd_receipt_field)
    return parser


if __name__ == "__main__":
    namespace = build_parser().parse_args(sys.argv[1:])
    sys.exit(namespace.fn(namespace))
