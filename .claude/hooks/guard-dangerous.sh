#!/usr/bin/env bash
set -euo pipefail

# Claude Code supplies JSON on stdin. Exit 2 blocks a tool call with this message.
input=$(cat)
if ! printf '%s' "$input" | jq -e . >/dev/null 2>&1; then
  echo "Blocked: guard could not parse the tool request. Check the hook JSON and retry." >&2
  exit 2
fi
tool=$(printf '%s' "$input" | jq -r '.tool_name // ""')
agent_type=$(printf '%s' "$input" | jq -r '.agent_type // ""')
command=$(printf '%s' "$input" | jq -r '.tool_input.command // ""')
path=$(printf '%s' "$input" | jq -r '.tool_input.file_path // .tool_input.path // ""')
lower_command=$(printf '%s' "$command" | tr '[:upper:]' '[:lower:]')
lower_path=$(printf '%s' "$path" | tr '[:upper:]' '[:lower:]')

block() {
  echo "Blocked: $1. Route this action through the owning agent and recorded human gate." >&2
  exit 2
}

# The path fence covers Read and common shell spellings; do not print secrets.
secret_pattern='(^|[/[:space:]"'\''=])([.]env([./[:space:]"'\'']|$)|secrets?/|[.]aws/credentials|[.]ssh/|[^/[:space:]]+[.]pem([[:space:]"'\'']|$)|[^/[:space:]]+[.]key([[:space:]"'\'']|$)|id_rsa|id_ed25519)'
if [[ "$lower_path" =~ $secret_pattern ]] || [[ "$lower_command" =~ $secret_pattern ]]; then
  block "secret file or credential path access"
fi

root=${CLAUDE_PROJECT_DIR:-$(pwd)}
relative=""
if [[ -n "$path" ]]; then
  # Resolve dot segments and symlinked parents; an external path is not a
  # ScholarChain constitutional file. Claude normally supplies absolute paths.
  if ! relative=$(python3 - "$root" "$path" <<'PY'
from pathlib import Path
import sys
root=Path(sys.argv[1]).resolve()
candidate=Path(sys.argv[2].replace('\\', '/'))
if not candidate.is_absolute():
    candidate=root/candidate
candidate=candidate.resolve(strict=False)
try:
    print(candidate.relative_to(root).as_posix())
except ValueError:
    print('')
PY
  ); then
    block "could not normalize a tool path"
  fi
fi
is_constitutional_path() {
  case "$1" in
    AGENTS.md|CLAUDE.md|.mcp.json|docs/agents.md|docs/agent-runs/README.md|.claude/*)
      [[ "$1" != ".claude/.last-test-run" ]]
      ;;
    *) return 1 ;;
  esac
}
if [[ "$tool" == "Write" || "$tool" == "Edit" ]]; then
  if [[ "$relative" == ".claude/.last-test-run" ]]; then
    block "test marker must be generated by successful sbt check"
  fi
  if is_constitutional_path "$relative" && [[ "$agent_type" != "factory-engineer" ]]; then
    block "constitutional file edit by ${agent_type:-main orchestrator}; use factory-engineer after human approval"
  fi
fi

if [[ "$tool" != "Bash" ]]; then
  exit 0
fi

# Shell mutation detection is conservative. Tool-path edits above are the stronger fence.
if [[ "$agent_type" != "factory-engineer" ]] &&
   [[ "$command" =~ (AGENTS[.]md|CLAUDE[.]md|[.]mcp[.]json|docs/agents[.]md|docs/agent-runs/README[.]md|[.]claude/) ]] &&
   [[ "$lower_command" =~ (\>\>?|(^|[[:space:]])(tee|cp|mv|rm|touch|chmod|install|patch|apply_patch|python3?|ruby)([[:space:]]|$)|sed[[:space:]]+-i|perl[[:space:]]+-pi) ]]; then
  block "possible constitutional file mutation by ${agent_type:-main orchestrator}"
fi

# Conservative pattern matching also blocks harmless quoted probes, as required.
[[ "$lower_command" =~ terraform[[:space:]]+([^[:cntrl:]]*[[:space:]])?(apply|destroy)([^a-z0-9_-]|$) ]] && block "terraform apply or destroy"
[[ "$lower_command" =~ git[[:space:]]+([^[:cntrl:]]*[[:space:]])?push([^[:cntrl:]]*)(--force(-with-lease)?|-f)([^a-z0-9_-]|$) ]] && block "force push"
[[ "$lower_command" =~ aws[[:space:]]+([^[:cntrl:]]*[[:space:]])?s3[[:space:]]+rm([^[:cntrl:]]*)--recursive ]] && block "recursive S3 deletion"
[[ "$lower_command" =~ aws[[:space:]]+([^[:cntrl:]]*[[:space:]])?s3[[:space:]]+rm([^a-z0-9_-]|$) ]] && block "S3 object deletion"
[[ "$lower_command" =~ aws[[:space:]]+([^[:cntrl:]]*[[:space:]])?(s3api|dynamodb|neptune|neptune-db|s3vectors|ecr|kms|emr|ec2)[[:space:]]+(delete-|terminate-|cancel-|stop-|remove-)([a-z0-9-]*) ]] && block "destructive AWS operation"
[[ "$lower_command" =~ aws[[:space:]]+([^[:cntrl:]]*[[:space:]])?emr[[:space:]]+(modify-instance|add-instance) ]] && block "unreviewed EMR scale change"
[[ "$lower_command" =~ aws[[:space:]]+([^[:cntrl:]]*[[:space:]])?autoscaling[[:space:]]+(update-auto-scaling-group|set-desired-capacity) ]] && block "unreviewed scale change"
[[ "$lower_command" =~ (drop[[:space:]]+(database|table)|truncate[[:space:]]+table|delete[[:space:]]+from) ]] && block "destructive database statement"
exit 0
